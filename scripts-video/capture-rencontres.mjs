console.log('après scroll', bb2 && {x:Math.round(bb2.x+bb2.width/2), y:Math.round(bb2.y+bb2.height/2)});
await btn.click(); await p.waitForTimeout(1800);
await p.screenshot({path:`${OUT}/evenements-inscrit.png`});
