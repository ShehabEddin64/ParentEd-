const bb = await btn.boundingBox();
console.log('bouton à', bb && {x:Math.round(bb.x+bb.width/2), y:Math.round(bb.y+bb.height/2)});
await btn.scrollIntoViewIfNeeded(); await p.waitForTimeout(600);
await p.screenshot({path:`${OUT}/evenements-avant.png`});
