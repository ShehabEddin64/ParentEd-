export const landingText: Record<Lang, LandingText> = { fr, en };
export function loadLang(): Lang {
  try {
    const saved = localStorage.getItem("parented-lang");
    if (saved === "en" || saved === "fr") return saved;
  } catch {
    /* ignore */
  }
  return navigator.language.toLowerCase().startsWith("en") ? "en" : "fr";
}
export function saveLang(lang: Lang) {
  try {
    localStorage.setItem("parented-lang", lang);
  } catch {
    /* ignore */
  }
}
